-- 여행 일정 저장 테이블 (Oracle, hr 계정)
-- TRIP_TITLE  : 여행 이름 (예: 부산 1박2일)
-- TRIP_DATE   : 방문 날짜
-- VISIT_ORDER : 그날 방문 순서
-- PLACE_NAME  : 장소명
-- CATEGORY    : 맛집 / 카페 / 관광지 / 숙소 등
-- ADDRESS     : 주소
-- PLACE_URL   : 카카오맵 장소 링크
-- MEMO        : 추천 이유, 메모
CREATE TABLE TRAVEL_PLAN (
    PLAN_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRIP_TITLE  VARCHAR2(200)  NOT NULL,
    TRIP_DATE   DATE           NOT NULL,
    VISIT_ORDER NUMBER(3)      DEFAULT 1,
    PLACE_NAME  VARCHAR2(200)  NOT NULL,
    CATEGORY    VARCHAR2(50),
    ADDRESS     VARCHAR2(300),
    PLACE_URL   VARCHAR2(500),
    MEMO        VARCHAR2(1000),
    CREATED_AT  DATE DEFAULT SYSDATE
);
